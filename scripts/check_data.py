"""Reject personal-data files (design/08-workflow.md §4-5).

The repo is public, and real journals are personal data. Spreadsheets and the app's snapshots
(`<module>.json.gz`, the journal's data) may only live in `design/mockups/` and
`tests/fixtures/`, which hold fictional data generated by repo scripts. OAuth secrets and
tokens and `.env` files are refused everywhere. `.gitignore` keeps the usual places out; this
also catches a file added by force or saved somewhere else.
Run by pre-commit with the staged paths, or by hand: `python scripts/check_data.py PATH...`.
"""

import fnmatch
import posixpath
import sys
from pathlib import PurePosixPath

SPREADSHEET_SUFFIXES = {".xlsx", ".xlsm", ".xls", ".ods", ".csv"}
DATA_SUFFIXES = (".json.gz",)  # app snapshots: a module's records
SECRET_NAMES = ("client_secret*.json", "*token*.json", ".env", ".env.*")  # anywhere
ALLOWED_DIRS = (PurePosixPath("design/mockups"), PurePosixPath("tests/fixtures"))


def is_forbidden(path: str) -> bool:
    """True for a path (relative to the repo root) that may hold personal data: a secret
    anywhere, a spreadsheet or snapshot outside the fictional-data folders."""
    p = PurePosixPath(posixpath.normpath(path))  # so `tests/fixtures/../x.xlsx` is caught
    name = p.name.lower()
    if any(fnmatch.fnmatch(name, pattern) for pattern in SECRET_NAMES):
        return True
    data = p.suffix.lower() in SPREADSHEET_SUFFIXES or name.endswith(DATA_SUFFIXES)
    if not data:
        return False
    return not any(p.is_relative_to(allowed) for allowed in ALLOWED_DIRS)


def main(paths: list[str]) -> int:
    forbidden = [path for path in paths if is_forbidden(path)]
    allowed = ", ".join(f"{d}/" for d in ALLOWED_DIRS)
    for path in forbidden:
        print(
            f"{path}: may hold personal data (journals, snapshots, secrets); "
            f"data files only in {allowed} (fictional)"
        )
    return 1 if forbidden else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
